def select_template_by_category(category: str) -> dict:
    """Простой роутинг — какой шаблон лучше подходит к категории.
    GPT-4o-mini может это переопределить, но это безопасный default."""
    cat_lower = (category or "").lower()
    matches: list[tuple[int, dict]] = []
    for tpl in ALL_TEMPLATES:
        score = sum(1 for kw in tpl["best_for_categories"] if kw in cat_lower)
        matches.append((score, tpl))
    matches.sort(key=lambda x: x[0], reverse=True)
    if matches[0][0] > 0:
        return matches[0][1]
    return TEMPLATE_A  # default


